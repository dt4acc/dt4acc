"""Write the static BESSY II injection twin PV list
(``custom_facility/bessyii_injection/pv_list.md``) from PV dumps of the
injection twin, the storage ring twin and the transfer line twin.

The injection twin serves the storage ring's PVs (as the ring twin), the
transfer line's supplies, magnets and monitors up to the septum exit (as the
transfer line twin, machine names), the transfer line's model PVs one level
down (``TL:``) and the hand over (``INJ:``, ``<bpm>:tbt:``). This script
checks that the dumps add up to exactly that, then lists the parts: the
ring's and the line's PVs by reference to their lists, the transfer line
model and hand over PVs in full. PV names are given without the twin's
prefix (``DT4ACC_PREFIX``).

    scripts/bessyii/dump_twin_pvs.sh <dump>       # with each twin running
    python scripts/bessyii_injection/make_pv_list.py <injection dump> <ring dump> <line dump>
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "src/dt4acc/custom_facility/bessyii_injection/pv_list.md"

NO = "no"
ACTS, RO = "acts", ""
PLANES = [("x", "horizontal position (m)"), ("xp", "horizontal angle (rad)"), ("y", "vertical position (m)"),
          ("yp", "vertical angle (rad)"), ("delta", "momentum offset (1)"), ("ct", "path length offset (m)")]

INJECTION = [
    ("Geometry: the line's reference against the ring's at the septum exit (ring = line + geometry)",
     [(f"INJ:geometry:{p}", d, ACTS, NO) for p, d in PLANES]),
    ("Beam leaving the line (line frame)",
     [(f"INJ:line_exit:{p}", d, RO, NO) for p, d in PLANES]),
    ("Injected beam at MSEPEXIT (ring frame)",
     [(f"INJ:injected:{p}", d, RO, NO) for p, d in PLANES]),
    ("Tracking in the ring", [
        ("INJ:n_turns", "turns tracked (1 ... 256)", ACTS, NO),
        ("INJ:tbt:x", "horizontal position at the ring BPMs: turn 1 at all BPMs, then turn 2, ... (m)", RO, NO),
        ("INJ:tbt:y", "vertical position at the ring BPMs, as INJ:tbt:x (m)", RO, NO),
        ("INJ:tbt:names", "the ring BPMs, in the order of INJ:tbt:x / y", RO, NO),
        ("INJ:survived", "particles still there after each turn", RO, NO),
        ("INJ:count", "hand overs computed so far", RO, NO),
    ]),
]
TBT_FIELDS = [("tbt:x", "horizontal position, turn after turn (m)", RO, NO),
              ("tbt:y", "vertical position, turn after turn (m)", RO, NO)]

HEADER = """\
# BESSY II injection twin: PV list

What the dt4acc BESSY II injection twin (storage ring + transfer line) serves: {n} PVs.
No values: read them from a running twin. Generated by
`scripts/bessyii_injection/make_pv_list.py` from running twins
(`scripts/bessyii/dump_twin_pvs.sh`), which checks that the parts below add up to
exactly what the twin serves. Names are given without the twin's prefix: the IOC
prepends `DT4ACC_PREFIX` (default: the user name), e.g. `<P>:Q1PDR:set`.

| part | PVs | names | listed in |
|---|---|---|---|
| storage ring | {n_ring} | as the storage ring twin | [`../bessyii/pv_list.md`](../bessyii/pv_list.md) |
| transfer line: supplies, magnets, monitors | {n_tl_dev} | machine names, as the transfer line twin | [`../bessytl/pv_list.md`](../bessytl/pv_list.md){tl_missing_note} |
| transfer line: model | {n_tl_model} | `TL:` + the transfer line twin's name (the ring has the same names) | below |
| hand over | {n_inj} | `INJ:...`, `<bpm>:tbt:...` | below |

Transfer line devices do not clash with the ring's: their names end in T, the ring's in R.
See [`README.md`](README.md) for how the parts work together.

Columns as in the ring's and the line's lists:

* **write**: *acts*: the twin acts on a write; empty: read only.
* **protocol**: *CA + PVA*: a record of the twin's soft IOC (`caget` / `pvget`, pyepics /
  p4p); *PVA*: the twin's own PV Access server only (structures).
* **machine**: *no*: twin only.
"""

TABLE_HEAD = ["| PV | | write | protocol | machine |", "|---|---|---|---|---|"]


def row(pv, desc, write, proto, machine):
    return f"| `{pv}` | {desc} | {write} | {proto} | {machine} |"


def read_dump(folder: Path):
    """{pv without the prefix: "CA + PVA" | "PVA"}"""
    pva = sorted({ln.strip() for ln in (folder / "pvs_by_server.txt").read_text().splitlines()
                  if ln.strip() and not ln.startswith("GUID")})
    ca = set((folder / "pvs_ca.txt").read_text().split())
    prefixes = {n.split(":", 1)[0] for n in pva}
    assert len(prefixes) == 1, f"expected one prefix, got {sorted(prefixes)[:5]}"
    return {n.split(":", 1)[1]: ("CA + PVA" if n in ca else "PVA") for n in pva}


def is_tl_model(pv: str) -> bool:
    """model PVs of the transfer line twin (the ring has the same names)"""
    return pv.startswith(("beam:", "survey:", "ORBITCC:"))


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("injection", type=Path, help="dump of the injection twin")
    p.add_argument("ring", type=Path, help="dump of the storage ring twin")
    p.add_argument("line", type=Path, help="dump of the transfer line twin")
    p.add_argument("--out", type=Path, default=OUT)
    return p.parse_args()


def main(a):
    inj, ring, line = read_dump(a.injection), read_dump(a.ring), read_dump(a.line)

    # the ring: exactly as the ring twin
    missing = sorted(set(ring) - set(inj))
    assert not missing, f"ring PVs the injection twin does not serve: {missing[:5]}"
    assert all(inj[pv] == p for pv, p in ring.items()), "a ring PV is served over another protocol"

    # the line's model one level down; its devices as in the line twin, up to the septum exit
    tl_model = {f"TL:{pv}": p for pv, p in line.items() if is_tl_model(pv)}
    missing = sorted(set(tl_model) - set(inj))
    assert not missing, f"transfer line model PVs not served: {missing[:5]}"
    tl_dev_all = {pv: p for pv, p in line.items() if not is_tl_model(pv)}
    tl_dev = {pv: p for pv, p in tl_dev_all.items() if pv in inj}
    tl_dev_missing = sorted(set(tl_dev_all) - set(tl_dev))
    clash = sorted(pv for pv in tl_dev if pv in ring)
    assert not clash, f"transfer line PVs with a ring name: {clash[:5]}"

    # the hand over: everything else
    rest = {pv: p for pv, p in inj.items() if pv not in ring and pv not in tl_model and pv not in tl_dev}
    named = {pv for _, rows in INJECTION for pv, *_ in rows}
    missing = sorted(named - set(rest))
    assert not missing, f"hand over PVs not served: {missing[:5]}"
    bpms = sorted({pv.rsplit(":", 2)[0] for pv in rest if re.search(r":tbt:[xy]$", pv) and not pv.startswith("INJ:")})
    tbt = {f"{b}:{f}" for b in bpms for f, *_ in TBT_FIELDS}
    unknown = sorted(set(rest) - named - tbt)
    assert not unknown, f"PVs of no part: {unknown[:10]}"
    n_inj = len(named) + len(tbt)
    assert len(ring) + len(tl_dev) + len(tl_model) + n_inj == len(inj)

    note = ""
    if tl_dev_missing:
        devs = sorted({pv.split(":", 1)[0] for pv in tl_dev_missing})
        note = (f", except {', '.join(f'`{d}`' for d in devs)}: after the septum exit, part of the ring's lattice"
                if devs else "")
    lines = [HEADER.format(n=len(inj), n_ring=len(ring), n_tl_dev=len(tl_dev), n_tl_model=len(tl_model),
                           n_inj=n_inj, tl_missing_note=note)]

    lines += ["## Transfer line model (`TL:`)", "",
              "The transfer line twin's model PVs (trajectory, optics, survey, BPM structures), as",
              "described in [`../bessytl/pv_list.md`](../bessytl/pv_list.md), up to the septum exit.", "",
              "```text", *sorted(tl_model), "```", ""]

    lines += ["## Hand over", "", "The beam leaving the line, put into the ring at `MSEPEXIT` and tracked turn",
              "by turn; recomputed whenever line, ring or these settings change.", ""]
    for title, rows in INJECTION:
        lines += [f"#### {title}", "", *TABLE_HEAD, *[row(pv, d, w, inj[pv], m) for pv, d, w, m in rows], ""]
    lines += [f"#### Ring BPMs, turn by turn ({len(bpms)})", "", *TABLE_HEAD]
    for f, d, w, m in TBT_FIELDS:
        (p,) = {inj[f"{b}:{f}"] for b in bpms}
        lines.append(row(f"<bpm>:{f}", d, w, p, m))
    lines += ["", "```text", " ".join(bpms), "```", ""]

    a.out.write_text("\n".join(lines))
    print(f"{a.out}: {len(inj)} PVs: ring {len(ring)}, transfer line devices {len(tl_dev)} "
          f"(not served: {len(tl_dev_missing)}), transfer line model {len(tl_model)}, hand over {n_inj}")


if __name__ == "__main__":
    main(parse_args())
