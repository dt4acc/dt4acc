BRHO = 5.0034611376381655

# the generated tables shipped with dt4acc (package resources)
DEFAULT_CONFIG_DIR = ("custom_facility", "maxiv_r1", "resources", "created")


class SetupFiles(BaseModel):
    """File names of the tables build_managers reads from its directory."""
    model_config = ConfigDict(frozen=True)

    yellow_pages: str = "maxiv_r1_yellow_pages_lookup_table.yml"
    liaison_manager_forward: str = "maxiv_r1_liaison_manager_forward_lookup_table.yml"
    liaison_manager_inverse: str = "maxiv_r1_liaison_manager_inverse_lookup_table.yml"
    translation_service: str = "maxiv_r1_translation_service_lookup_table.yml"
    translation_service_curves: str = "maxiv_r1_translation_service_curves.yml"



class TranslatorService:
    """Local TranslatorService: takes ready-built conversions directly,
    since TranslatorLookupTable cannot express curve-based conversions."""

    def __init__(self, lut: Mapping[ConversionID, StateConversion]):
        self.lut = lut

    def get(self, id_: ConversionID) -> StateConversion:
        return self.lut[id_]


@functools.lru_cache(maxsize=1)
def load_managers():
    """The managers from DT4ACC_MAXIV_R1_SETUP_DIR, else the packaged tables."""
    return build_managers(os.environ.get("DT4ACC_MAXIV_R1_SETUP_DIR") or DEFAULT_CONFIG_DIR)


def build_managers(
    config_dir: Union[str, Path, Tuple[str, ...]] = DEFAULT_CONFIG_DIR,
    setup_files: Optional[SetupFiles] = None,
):
    """config_dir: a directory, or a path inside the dt4acc package (tuple)."""
    if BRHO is None:
        raise RuntimeError("brho for maxiv_r1 is a placeholder; set BRHO first")
    setup_files = setup_files or SetupFiles()

    obj = load_file(config_dir, setup_files.yellow_pages)
    yp = YellowPages(jsons.load(obj))

    obj = load_file(config_dir, setup_files.liaison_manager_forward)
    lm_fwd = jsons.load(obj, LiaisonManagerForwardLookupTable)
    obj = load_file(config_dir, setup_files.liaison_manager_inverse)
    lm_inv = jsons.load(obj, LiaisonManagerInverseLookupTable)
    lm = LiaisonManager(forward_lut=lm_fwd, inverse_lut=lm_inv)

    obj = load_file(config_dir, setup_files.translation_service)
    ts_lut = jsons.load(obj, TranslatorLookupTable)
    conversions = {
        entry.conversion_id: create_translation_object_for_data_model(entry.conversion_info, BRHO)
        for entry in ts_lut.lut
    }
    for entry in load_file(config_dir, setup_files.translation_service_curves)["lut"]:
        cid = entry["conversion_id"]
        conversion_id = ConversionID(
            lattice_property_id=LatticeElementPropertyID(**cid["lattice_property_id"]),
            device_property_id=DevicePropertyID(**cid["device_property_id"]),
        )
        points = [CurvePoint(indep=indep, dep=dep) for indep, dep in entry["points"]]
        conversions[conversion_id] = EnergyIndependentCurveUnitConversion(
            fwd_points=points,
            bwd_points=points,
            brho=BRHO,
            flip_dep_sign=entry["flip_dep_sign"],
            length=entry["length"],
        )
    ts = TranslatorService(lut=conversions)
    return yp, lm, ts


def load_file(config_dir: Union[str, Path, Tuple[str, ...]], file_name: str):
    if isinstance(config_dir, tuple):
        t_file = files("dt4acc").joinpath(*config_dir, file_name)
    else:
        t_file = Path(config_dir) / file_name
    with open(t_file, "rt") as fp:
        obj = yaml.load(fp, yaml.Loader)
    return obj
